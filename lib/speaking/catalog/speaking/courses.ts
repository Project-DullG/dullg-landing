export function safePreferences(value: unknown) {
  const fallback = {
    course: "week" as CourseId,
    day: 0,
    minutes: 60 as 60 | 90 | 120,
  };
  if (!value || typeof value !== "object") return fallback;
  const v = value as Record<string, unknown>;
  const course = courses.find((c) => c.id === v.course);
  if (!course) return fallback;
  return {
    course: course.id,
    day:
      Number.isInteger(v.day) && Number(v.day) >= 0 && Number(v.day) < course.days.length
        ? Number(v.day)
        : 0,
    minutes: ([60, 90, 120].includes(Number(v.minutes)) ? Number(v.minutes) : 60) as 60 | 90 | 120,
  };
}
